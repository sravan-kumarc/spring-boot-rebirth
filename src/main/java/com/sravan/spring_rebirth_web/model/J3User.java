package com.sravan.spring_rebirth_web.model;

public class J3User {
    private String name;
    private String role;

    public J3User() {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }
}
